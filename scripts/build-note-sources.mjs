// Compiling and reading results

// Up to date when the last compile here used the same source, or when a PDF
// newer than the .tex exists (compiled by another step, as in CI).
async function isCompiled(dir, file, expectedHash) {
  const pdf = path.join(dir, file.replace(/\.tex$/, ".pdf"));
  const stamp = await readFile(path.join(dir, ".compiled-hash"), "utf8").catch(() => "");
  if (stamp === expectedHash && (await exists(pdf))) return true;
  const [pdfTime, texTime] = await Promise.all(
    [pdf, path.join(dir, file)].map((f) => stat(f).then((s) => s.mtimeMs).catch(() => 0))
  );
  return pdfTime > 0 && pdfTime >= texTime && stamp === "";
}

async function compile(dir, file, expectedHash) {
  const pdf = path.join(dir, file.replace(/\.tex$/, ".pdf"));
  const stamp = path.join(dir, ".compiled-hash");

  try {
    await run("latexmk", ["-pdf", "-f", "-g", "-interaction=nonstopmode", "-silent", file], {
      cwd: dir,
      maxBuffer: 64 * 1024 * 1024,
      timeout: 15 * 60 * 1000
    });
  } catch (error) {
    // latexmk -f keeps going past recoverable errors; a PDF still counts.
    if (!(await exists(pdf))) {
      const log = await readFile(path.join(dir, file.replace(/\.tex$/, ".log")), "utf8").catch(() => "");
      const reason = log.match(/^! (.+)$/m)?.[1] || error.message.split("\n")[0];
      console.warn(`  ${path.relative(projectRoot, dir)}/${file} did not compile: ${reason}`);
      // Not retried until the source changes.
      await writeFile(path.join(dir, ".failed-hash"), expectedHash, "utf8");
      return false;
    }
  }
  await writeFile(stamp, expectedHash, "utf8");
  await rm(path.join(dir, ".failed-hash"), { force: true });
  return true;
}

function parseAux(aux) {
  const marks = {};
  const labels = {};
  for (const match of aux.matchAll(/\\webnumber\{([se]\d+)\}\{([^{}]*)\}/g)) marks[match[1]] = match[2];
  for (const match of aux.matchAll(/\\newlabel\{([^{}]+)\}\{\{([^{}]*)\}/g)) {
    const [key, number] = [match[1], match[2]];
    if (key.endsWith("@cref")) {
      const cref = number.match(/^\[([^\]]+)\](?:\[[^\]]*\])*(.*)$/);
      if (cref) {
        const base = key.slice(0, -"@cref".length);
        labels[base] = { ...(labels[base] || {}), type: cref[1] };
      }
    } else {
      labels[key] = { ...(labels[key] || {}), number };
    }
  }
  return { marks, labels };
}

async function finishLatex(note, prepared) {
  const workDir = path.join(generatedRoot, note.name);
  const meta = {
    theorems: prepared.theorems,
    boxes: prepared.boxes,
    figureCount: prepared.figureCount,
    figuresReady: false,
    sections: null,
    environments: null,
    labels: {}
  };

  const aux = await readFile(path.join(workDir, "numbers", "main.aux"), "utf8").catch(() => "");
  if (aux) {
    const { marks, labels } = parseAux(aux);
    const list = (prefix, count) => {
      const values = Array.from({ length: count }, (_, i) => marks[`${prefix}${i}`]);
      return values.every((value) => value !== undefined) ? values : null;
    };
    meta.sections = list("s", prepared.sectionCount);
    meta.environments = list("e", prepared.envCount);
    meta.labels = labels;
  }

  const pdf = path.join(workDir, "figures", "figures.pdf");
  if (prepared.figureCount && (await exists(pdf)) && (await hasCommand("pdftocairo", ["-v"]))) {
    const { stdout } = await run("pdfinfo", [pdf]);
    const pages = Number(stdout.match(/^Pages:\s+(\d+)/m)?.[1] || 0);
    if (pages === prepared.figureCount) {
      const svgDir = path.join(workDir, "figures", "svg");
      await mkdir(svgDir, { recursive: true });
      const pdfTime = (await stat(pdf)).mtimeMs;
      const pending = [];
      for (let page = 1; page <= pages; page += 1) {
        const svg = path.join(svgDir, `fig-${page}.svg`);
        const svgTime = await stat(svg).then((s) => s.mtimeMs).catch(() => 0);
        if (svgTime < pdfTime) pending.push([page, svg]);
      }
      for (let i = 0; i < pending.length; i += 8) {
        await Promise.all(
          pending.slice(i, i + 8).map(([page, svg]) =>
            run("pdftocairo", ["-svg", "-f", String(page), "-l", String(page), pdf, svg])
          )
        );
      }
      meta.figuresReady = true;
    } else {
      console.warn(`  ${note.source}: expected ${prepared.figureCount} figures, compiled PDF has ${pages} pages`);
    }
  }

  if (meta.sections === null || meta.environments === null) {
    console.warn(`  ${note.source}: numbering markers missing; the page falls back to pandoc's numbering`);
  }
  await writeIfChanged(path.join(workDir, "meta.json"), `${JSON.stringify(meta, null, 2)}\n`);
}

async function publishFigures(note) {
  const svgDir = path.join(generatedRoot, note.name, "figures", "svg");
  const outDir = path.join(projectRoot, "docs", note.folder, "figures");
  const files = await readdir(svgDir).catch(() => []);
  if (!files.length) return;
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });
  await Promise.all(files.map((file) => copyFile(path.join(svgDir, file), path.join(outDir, file))));
}

