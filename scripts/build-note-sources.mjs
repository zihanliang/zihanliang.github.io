// LaTeX source scanning

// Index of the character that closes the group opened at text[start].
function closeGroup(text, start, open = "{", close = "}") {
  let depth = 0;
  for (let i = start; i < text.length; i += 1) {
    const char = text[i];
    if (char === "\\") {
      i += 1;
    } else if (char === open) {
      depth += 1;
    } else if (char === close) {
      depth -= 1;
      if (depth === 0) return i;
    }
  }
  return -1;
}

function skipSpaces(text, index) {
  while (index < text.length && /\s/.test(text[index])) index += 1;
  return index;
}

// Skips an optional [..] argument starting at index (after spaces).
function skipOptional(text, index) {
  const next = skipSpaces(text, index);
  if (text[next] !== "[") return index;
  const end = closeGroup(text, next, "[", "]");
  return end === -1 ? index : end + 1;
}

// Replaces comments with a bare "%" (keeping LaTeX's line joining) outside
// verbatim environments and inline \verb / \lstinline arguments.
function stripComments(text) {
  const lines = text.split("\n");
  let verbatimEnd = null;

  return lines
    .map((line) => {
      if (verbatimEnd) {
        if (line.includes(verbatimEnd)) verbatimEnd = null;
        return line;
      }
      const opened = VERBATIM_ENVIRONMENTS.find((env) => line.includes(`\\begin{${env}}`));
      if (opened && !line.includes(`\\end{${opened}}`)) {
        verbatimEnd = `\\end{${opened}}`;
        return line;
      }

      for (let i = 0; i < line.length; i += 1) {
        const char = line[i];
        if (char === "\\") {
          const inline = line.slice(i).match(/^\\(verb\*?|lstinline)(\[[^\]]*\])?/);
          if (inline) {
            let j = i + inline[0].length;
            const delimiter = line[j];
            const closing = delimiter === "{" ? "}" : delimiter;
            const end = line.indexOf(closing, j + 1);
            if (delimiter && end !== -1) {
              i = end;
              continue;
            }
          }
          i += 1;
        } else if (char === "%") {
          return `${line.slice(0, i)}%`;
        }
      }
      return line;
    })
    .join("\n");
}

async function expandInputs(file, seen = new Set()) {
  if (seen.has(file)) throw new Error(`Circular \\input of ${file}`);
  seen.add(file);
  const text = stripComments(await readFile(file, "utf8"));
  const pattern = /\\(input|include)\s*\{([^}]+)\}/g;
  let result = "";
  let last = 0;
  for (const match of text.matchAll(pattern)) {
    let target = path.resolve(path.dirname(file), match[2].trim());
    if (!(await exists(target)) && (await exists(`${target}.tex`))) target = `${target}.tex`;
    if (!(await exists(target))) continue;
    result += text.slice(last, match.index) + (await expandInputs(target, seen));
    last = match.index + match[0].length;
  }
  seen.delete(file);
  return result + text.slice(last);
}

// [start, end) ranges of verbatim environments, which are never scanned.
function verbatimRanges(text) {
  const ranges = [];
  for (const env of VERBATIM_ENVIRONMENTS) {
    const begin = `\\begin{${env}}`;
    const end = `\\end{${env}}`;
    let index = text.indexOf(begin);
    while (index !== -1) {
      const close = text.indexOf(end, index);
      if (close === -1) break;
      ranges.push([index, close + end.length]);
      index = text.indexOf(begin, close);
    }
  }
  return ranges;
}

function inRanges(index, ranges) {
  return ranges.some(([start, end]) => index >= start && index < end);
}

// Outermost figure environments and macros, in document order.
function findFigures(body) {
  const skip = verbatimRanges(body);
  const names = FIGURE_ENVIRONMENTS.map((name) => name.replace("*", "\\*")).join("|");
  const pattern = new RegExp(`\\\\(begin|end)\\{(${names})\\}`, "g");
  const figures = [];
  let depth = 0;
  let start = 0;
  let kind = "";

  for (const match of body.matchAll(pattern)) {
    if (inRanges(match.index, skip)) continue;
    if (match[1] === "begin") {
      if (depth === 0) {
        start = match.index;
        kind = match[2];
      }
      depth += 1;
    } else if (depth > 0) {
      depth -= 1;
      if (depth === 0) figures.push({ start, end: match.index + match[0].length, kind });
    }
  }

  for (const macro of FIGURE_MACROS) {
    const macroPattern = new RegExp(`\\\\${macro}\\s*\\{`, "g");
    for (const match of body.matchAll(macroPattern)) {
      if (inRanges(match.index, skip) || figures.some((f) => match.index >= f.start && match.index < f.end)) continue;
      const end = closeGroup(body, match.index + match[0].length - 1);
      if (end !== -1) figures.push({ start: match.index, end: end + 1, kind: macro });
    }
  }

  figures.sort((a, b) => a.start - b.start);

  // A picture that is the whole of a \[ ... \] display takes the display with it.
  for (const figure of figures) {
    const before = body.slice(0, figure.start).match(/\\\[\s*$/);
    const after = body.slice(figure.end).match(/^\s*\\\]/);
    if (before && after) {
      figure.start -= before[0].length;
      figure.end += after[0].length;
      figure.display = true;
    }
  }
  return figures;
}

// Theorem-like environments declared with \newtheorem, with their style.
function parseTheorems(preamble) {
  const theorems = {};
  let style = "plain";
  const pattern = /\\theoremstyle\s*\{(\w+)\}|\\newtheorem\s*\{([\w*]+)\}\s*(?:\[\w+\])?\s*\{([^}]*)\}/g;
  for (const match of preamble.matchAll(pattern)) {
    if (match[1]) style = match[1];
    else theorems[match[2]] = { title: match[3], style, numbered: !match[2].endsWith("*") };
  }
  return theorems;
}

// \newenvironment / \newtcolorbox definitions that draw a tcolorbox. They are
// dropped from the copy pandoc reads, so the boxes arrive as Divs named after
// the environment; their titles are kept for the reader page.
function extractBoxes(preamble) {
  const boxes = {};
  const removals = [];
  const pattern = /\\(newenvironment|renewenvironment|newtcolorbox)\s*\{(\w+)\}/g;

  for (const match of preamble.matchAll(pattern)) {
    let index = skipOptional(preamble, match.index + match[0].length);
    index = skipOptional(preamble, index);
    const groups = match[1] === "newtcolorbox" ? 1 : 2;
    let end = index;
    let definition = "";
    for (let i = 0; i < groups; i += 1) {
      const open = skipSpaces(preamble, end);
      if (preamble[open] !== "{") break;
      const close = closeGroup(preamble, open);
      if (close === -1) break;
      definition += preamble.slice(open, close + 1);
      end = close + 1;
    }
    if (match[1] !== "newtcolorbox" && !definition.includes("tcolorbox")) continue;
    const title =
      definition.match(/title\s*=\s*\{?([^,}\]\n]+)/)?.[1] ||
      definition.match(/\\textbf\s*\{([^}]+)\}/)?.[1] ||
      "";
    boxes[match[2]] = title.trim().replace(/[.:]$/, "");
    removals.push([match.index, end]);
  }

  let webPreamble = preamble;
  for (const [start, end] of removals.reverse()) {
    webPreamble = webPreamble.slice(0, start) + webPreamble.slice(end);
  }
  return { boxes, webPreamble };
}

// Macros that add a part-level contents entry (\addcontentsline{toc}{part})
// head a group of sections, so pandoc reads their \section* as \part*.
function promotePartMacros(preamble) {
  let result = preamble;
  const heads = [...preamble.matchAll(/\\(?:re)?newcommand\s*\{\\\w+\}(?:\s*\[\d\])?\s*\{/g)].reverse();
  for (const head of heads) {
    const open = head.index + head[0].length - 1;
    const close = closeGroup(preamble, open);
    if (close === -1) continue;
    const definition = preamble.slice(open, close + 1);
    if (!definition.includes("\\addcontentsline{toc}{part}")) continue;
    result = result.slice(0, open) + definition.replace(/\\section\*/g, "\\part*") + result.slice(close + 1);
  }
  return result;
}

// Inserts \webnumber markers after numbered sectioning commands and at the start
// of numbered theorem-like environments, outside figures and verbatim text.
function markNumbers(body, theorems, figures) {
  const skip = [...verbatimRanges(body), ...figures.map((f) => [f.start, f.end])];
  const envNames = Object.keys(theorems).filter((name) => theorems[name].numbered);
  const inserts = [];
  let sectionCount = 0;
  let envCount = 0;

  const pattern = new RegExp(
    `\\\\(${SECTION_COMMANDS.join("|")})(?![a-zA-Z*])|\\\\begin\\{(${envNames.join("|") || "\\b\\B"})\\}`,
    "g"
  );
  for (const match of body.matchAll(pattern)) {
    if (inRanges(match.index, skip)) continue;
    let index = skipOptional(body, match.index + match[0].length);
    if (match[1]) {
      const open = skipSpaces(body, index);
      if (body[open] !== "{") continue;
      index = closeGroup(body, open) + 1;
      inserts.push([index, `\\webmark{s${sectionCount}}`]);
      sectionCount += 1;
    } else {
      inserts.push([index, `\\webmark{e${envCount}}`]);
      envCount += 1;
    }
  }

  let marked = body;
  for (const [index, text] of inserts.reverse()) marked = marked.slice(0, index) + text + marked.slice(index);
  return { marked, sectionCount, envCount };
}

function figureSnippet(body, figure) {
  let snippet = body.slice(figure.start, figure.end);
  if (figure.display) {
    snippet = `$\\displaystyle ${snippet.replace(/^\\\[/, "").replace(/\\\]$/, "")}$`;
  }
  if (figure.kind.startsWith("algorithm")) {
    snippet = snippet.replace(/^\\begin\{algorithm\*?\}(\s*\[[^\]]*\])?/, "\\begin{algorithm}[H]");
    snippet = snippet.replace(/\\end\{algorithm\*\}$/, "\\end{algorithm}");
  }
  if (figure.kind.startsWith("algorithm") || figure.kind === "dirtree") {
    snippet = `\\begin{minipage}{\\textwidth}\n${snippet}\n\\end{minipage}`;
  }
  return snippet;
}

function hash(text) {
  return createHash("sha1").update(text).digest("hex");
}

async function prepareLatex(note) {
  const source = path.join(projectRoot, note.source);
  const workDir = path.join(generatedRoot, note.name);
  const expanded = await expandInputs(source);
  const beginDocument = expanded.indexOf("\\begin{document}");
  const endDocument = expanded.lastIndexOf("\\end{document}");
  if (beginDocument === -1 || endDocument === -1) throw new Error(`${note.source} has no document body`);

  const preamble = expanded.slice(0, beginDocument);
  const body = expanded.slice(beginDocument + "\\begin{document}".length, endDocument);
  const theorems = parseTheorems(preamble);
  const { boxes, webPreamble } = extractBoxes(preamble);
  const figures = findFigures(body);

  // Settings shared by both compiles: images resolve from the note folder, and
  // Latin Modern keeps text scalable (crisp SVG text, and microtype's font
  // expansion works even where TeX Live lacks the cm-super fonts).
  const noteDir = path.join(projectRoot, note.folder);
  const compileSetup = (dir) => {
    const relative = path.relative(dir, noteDir).split(path.sep).join("/");
    return `\\usepackage{lmodern}\n\\graphicspath{{${relative}/}}\n`;
  };

  // The copy pandoc reads.
  let webBody = body;
  figures.forEach((figure, index) => {
    figure.index = index + 1;
  });
  for (const figure of [...figures].reverse()) {
    const labels = [...body.slice(figure.start, figure.end).matchAll(/\\label\s*\{([^}]+)\}/g)]
      .map((match) => `\\label{${match[1]}}`)
      .join("");
    webBody =
      webBody.slice(0, figure.start) +
      `\\includegraphics{figures/fig-${figure.index}.svg}${labels}` +
      webBody.slice(figure.end);
  }
  // LaTeX leaves \paragraph headings unnumbered (secnumdepth 3); tell pandoc so.
  webBody = webBody.replace(/\\(sub)?paragraph(?![a-zA-Z*])/g, (command) => `${command}*`);
  const webTex = `${promotePartMacros(webPreamble)}\\begin{document}${webBody}\\end{document}\n`;

  // The full document with number markers.
  const numbersDir = path.join(workDir, "numbers");
  const { marked, sectionCount, envCount } = markNumbers(body, theorems, figures);
  const numbersTex =
    preamble +
    compileSetup(numbersDir) +
    "\\makeatletter\n" +
    "\\newcommand{\\webnumber}[2]{}\n" +
    "\\newcommand{\\webmark}[1]{\\immediate\\write\\@auxout{\\string\\webnumber{#1}{\\@currentlabel}}}\n" +
    "\\makeatother\n" +
    `\\begin{document}${marked}\\end{document}\n`;

  // One preview page per figure.
  const figuresDir = path.join(workDir, "figures");
  const figuresTex =
    preamble +
    compileSetup(figuresDir) +
    "\\usepackage[active,tightpage]{preview}\n\\setlength\\PreviewBorder{6pt}\n" +
    "\\begin{document}\n" +
    figures.map((figure) => `\\begin{preview}\n${figureSnippet(body, figure)}\n\\end{preview}\n`).join("\n") +
    "\\end{document}\n";

  await writeIfChanged(path.join(workDir, "web.tex"), webTex);
  await writeIfChanged(path.join(numbersDir, "main.tex"), numbersTex);
  if (figures.length) await writeIfChanged(path.join(figuresDir, "figures.tex"), figuresTex);

  const prepared = {
    theorems,
    boxes,
    figureCount: figures.length,
    sectionCount,
    envCount,
    hashes: { numbers: hash(numbersTex), figures: figures.length ? hash(figuresTex) : null }
  };
  await writeIfChanged(path.join(workDir, "prepared.json"), `${JSON.stringify(prepared, null, 2)}\n`);
  return prepared;
}

