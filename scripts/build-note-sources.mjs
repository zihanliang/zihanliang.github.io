// Prepares study notes that have a web version (the "source" field in
// data/notes/sections.json). Each such note lives in its own folder,
// notes/<name>/, holding either a Markdown file or a LaTeX project.
//
// For every web note this script writes notes/<name>/index.qmd, a small
// generated stub that Quarto renders into the reader page; the Lua filter
// scripts/note-reader.lua then reads the real source.
//
// LaTeX notes need extra work, all kept in _generated/latex-notes/<name>/:
//   web.tex          the expanded document handed to pandoc, with TikZ
//                    pictures, algorithms, and directory trees replaced by
//                    SVG images
//   figures/         a preview-mode document holding just those pictures,
//                    compiled to PDF and split into one SVG per picture
//   numbers/         the full document with markers, compiled so the web page
//                    can show the PDF's own section, theorem, equation, and
//                    cross-reference numbers (read from its .aux file)
//   meta.json        environment names, box titles, numbers, figure count
//
// Usage:
//   node scripts/build-note-sources.mjs            prepare, compile, finish
//   node scripts/build-note-sources.mjs --prepare  write stubs and .tex files only
//   node scripts/build-note-sources.mjs --finish   read compiled output only
//   node scripts/build-note-sources.mjs --publish  copy figure SVGs into docs/
//
// Compiling needs latexmk and pdflatex; splitting figures needs Poppler
// (pdfinfo, pdftocairo). Without them the pages still render, with links to
// the PDF in place of the figures. Compiles are skipped when the generated
// .tex files have not changed since the last successful run.

import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { access, copyFile, mkdir, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";
import path from "node:path";

const run = promisify(execFile);
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generatedRoot = path.join(projectRoot, "_generated", "latex-notes");

const FIGURE_ENVIRONMENTS = ["tikzpicture", "tikzcd", "algorithm", "algorithm*"];
const FIGURE_MACROS = ["dirtree"];
const VERBATIM_ENVIRONMENTS = ["lstlisting", "verbatim", "Verbatim", "minted", "comment"];
const SECTION_COMMANDS = ["part", "section", "subsection", "subsubsection"];

const mode = process.argv[2] || "--all";

async function exists(file) {
  try {
    await access(file);
    return true;
  } catch {
    return false;
  }
}

async function writeIfChanged(file, content) {
  try {
    if ((await readFile(file, "utf8")) === content) return false;
  } catch {
    // Missing file: write it below.
  }
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, content, "utf8");
  return true;
}

async function hasCommand(command, args = ["--version"]) {
  try {
    await run(command, args);
    return true;
  } catch {
    return false;
  }
}

async function readWebNotes() {
  const catalog = JSON.parse(await readFile(path.join(projectRoot, "data/notes/sections.json"), "utf8"));
  return (catalog.sections || [])
    .flatMap((section) => section.items || [])
    .filter((note) => note.source && note.status !== "upcoming")
    .map((note) => ({
      ...note,
      folder: path.posix.dirname(note.source),
      name: path.posix.basename(path.posix.dirname(note.source)),
      isLatex: /\.tex$/i.test(note.source)
    }));
}

async function writeStub(note) {
  const stub = [
    "---",
    `# Generated by scripts/build-note-sources.mjs. Edit ${path.posix.basename(note.source)} instead.`,
    `note-source: ${JSON.stringify(path.posix.basename(note.source))}`,
    "---",
    ""
  ].join("\n");
  await writeIfChanged(path.join(projectRoot, note.folder, "index.qmd"), stub);
}

