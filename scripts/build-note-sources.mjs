const notes = await readWebNotes();
const latexNotes = notes.filter((note) => note.isLatex);

if (mode === "--publish") {
  await Promise.all(latexNotes.map(publishFigures));
  console.log("Published LaTeX note figures.");
  process.exit(0);
}

if (mode !== "--finish") await Promise.all(notes.map(writeStub));

const prepared = new Map();
for (const note of latexNotes) {
  if (mode === "--finish") {
    prepared.set(note, JSON.parse(await readFile(path.join(generatedRoot, note.name, "prepared.json"), "utf8")));
  } else {
    prepared.set(note, await prepareLatex(note));
  }
}

if (mode === "--all" && latexNotes.length) {
  const canCompile = (await hasCommand("latexmk")) && (await hasCommand("pdflatex"));
  await Promise.all(
    latexNotes.map(async (note) => {
      const info = prepared.get(note);
      const workDir = path.join(generatedRoot, note.name);
      const needs = [["numbers", "main.tex", info.hashes.numbers]];
      if (info.figureCount) needs.push(["figures", "figures.tex", info.hashes.figures]);
      for (const [dir, file, expected] of needs) {
        const target = path.join(workDir, dir);
        if (await isCompiled(target, file, expected)) continue;
        const failed = await readFile(path.join(target, ".failed-hash"), "utf8").catch(() => "");
        if (failed === expected) {
          console.warn(`  ${note.source}: ${dir} failed to compile last time; skipped until the source changes`);
          continue;
        }
        if (!canCompile) {
          console.warn(`  ${note.source}: ${dir} changed but latexmk/pdflatex is not available`);
          continue;
        }
        console.log(`  Compiling ${note.source} (${dir})...`);
        await compile(target, file, expected);
      }
    })
  );
}

if (mode !== "--prepare") {
  for (const note of latexNotes) await finishLatex(note, prepared.get(note));
}

console.log(`Prepared ${notes.length} web notes (${latexNotes.length} from LaTeX).`);
